def _service_key(name: str) -> str:
    return f"(null) - {name} - runWorkflowAsService"


def _workflow_path(name: str) -> Path:
    return Path.home() / "Library" / "Services" / f"{name}.workflow"


def _remove_service(name: str) -> None:
    shutil.rmtree(_workflow_path(name), ignore_errors=True)
    # `defaults delete` can't remove a key nested in a dict, so go through CFPreferences.
    from Foundation import (
        CFPreferencesAppSynchronize,
        CFPreferencesCopyAppValue,
        CFPreferencesSetAppValue,
    )

    status = CFPreferencesCopyAppValue("NSServicesStatus", "pbs")
    if status is not None and _service_key(name) in status:
        status = dict(status)
        del status[_service_key(name)]
        CFPreferencesSetAppValue("NSServicesStatus", status, "pbs")
        CFPreferencesAppSynchronize("pbs")


def _refresh_services() -> None:
    subprocess.run(["/System/Library/CoreServices/pbs", "-update"], check=False)
    subprocess.run(["/System/Library/CoreServices/pbs", "-flush"], check=False)


def install_service() -> None:
    """Right-click → Services → "Susurro: Speak selection". No hotkey: the app owns it."""
    # Also clears any old Services hotkey, which would fire alongside the app's own.
    for name in (SERVICE_NAME, *LEGACY_SERVICE_NAMES):
        _remove_service(name)
    contents = WORKFLOW / "Contents"
    contents.mkdir(parents=True, exist_ok=True)
    # No CFBundleIdentifier on purpose, like Automator-made workflows.
    info = {
        "CFBundleDevelopmentRegion": "en",
        "CFBundleName": SERVICE_NAME,
        "NSServices": [{
            "NSMenuItem": {"default": SERVICE_NAME},
            "NSMessage": "runWorkflowAsService",
            "NSSendTypes": ["public.utf8-plain-text"],
            "NSRequiredContext": {},
        }],
    }
    (contents / "Info.plist").write_bytes(plistlib.dumps(info))
    (contents / "document.wflow").write_bytes(plistlib.dumps(_workflow_document()))

    _refresh_services()


# ---------------------------------------------------------------- login agent


def _launchctl(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["launchctl", *args], capture_output=True, text=True)


def install_agent() -> None:
    """Run the menu bar app at login, and as its own process: the Accessibility permission
    then belongs to Susurro's Python, not to whichever terminal launched it."""
    python = PROJECT / ".venv" / "bin" / "python"
    path = ":".join([str(Path.home() / ".local" / "bin"), "/opt/homebrew/bin",
                     "/usr/local/bin", "/usr/bin", "/bin", "/usr/sbin", "/sbin"])
    plist = {
        "Label": AGENT_LABEL,
        "ProgramArguments": [str(python), "-m", "susurro", "app"],
        "WorkingDirectory": str(PROJECT),
        "EnvironmentVariables": {"PATH": path},
        "RunAtLoad": True,
        "KeepAlive": {"SuccessfulExit": False},  # restart on crash, not after "Quit"
        "ProcessType": "Interactive",
        "StandardOutPath": str(LOG),
        "StandardErrorPath": str(LOG),
    }
    AGENT_PLIST.parent.mkdir(parents=True, exist_ok=True)
    LOG.parent.mkdir(parents=True, exist_ok=True)
    domain = f"gui/{os.getuid()}"
    _launchctl("bootout", f"{domain}/{AGENT_LABEL}")
    AGENT_PLIST.write_bytes(plistlib.dumps(plist))
    r = _launchctl("bootstrap", domain, str(AGENT_PLIST))
    if r.returncode != 0:
        raise SystemExit(f"launchctl bootstrap failed: {r.stderr.strip()}")


def uninstall_agent() -> None:
    _launchctl("bootout", f"gui/{os.getuid()}/{AGENT_LABEL}")
    AGENT_PLIST.unlink(missing_ok=True)


def cmd_install(_: argparse.Namespace) -> int:
    # Stop any app instance started by hand, so the agent's instance owns the port.
    subprocess.run(["pkill", "-f", "susurro app"], capture_output=True)
    install_service()
    install_agent()
    s = config.load()
    from .hotkey import pretty

    print(f"Installed. Susurro starts at login; shortcut: {pretty(s.hotkey)}.")
    print("First run: allow Accessibility for Susurro's Python when macOS asks "
          "(System Settings → Privacy & Security → Accessibility).")
    print(f"Log: {LOG}")
    return 0


def cmd_uninstall(_: argparse.Namespace) -> int:
    uninstall_agent()
    for name in (SERVICE_NAME, *LEGACY_SERVICE_NAMES):
        _remove_service(name)
    _refresh_services()
    print("Uninstalled.")
    return 0


def main() -> None:
    ap = argparse.ArgumentParser(prog="susurro", description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("app", help="open the menu bar app (and the local service)")
    sp = sub.add_parser("speak", help="speak a text (argument or stdin)")
    sp.add_argument("text", nargs="*")
    sp.add_argument("--mode", choices=list(MODES))
    sp.add_argument("--lang", choices=["auto", *LANGUAGES], help="speech language")
    sub.add_parser("stop", help="stop the audio")
    sub.add_parser("status", help="app status")
    sub.add_parser("install", help="start at login + right-click Services entry")
    sub.add_parser("uninstall", help="remove the login agent and the Services entry")
    args = ap.parse_args()
    fn = {
        "app": cmd_app, "speak": cmd_speak, "stop": cmd_stop, "status": cmd_status,
        "install": cmd_install, "uninstall": cmd_uninstall,
    }[args.cmd]
    sys.exit(fn(args))
