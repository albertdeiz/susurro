BASE = f"http://127.0.0.1:{PORT}"
PROJECT = Path(__file__).resolve().parent.parent
SERVICE_NAME = "Susurro: Speak selection"
LEGACY_SERVICE_NAMES = ["Susurro: escuchar selección"]
WORKFLOW = Path.home() / "Library" / "Services" / f"{SERVICE_NAME}.workflow"
AGENT_LABEL = "com.susurro.app"
AGENT_PLIST = Path.home() / "Library" / "LaunchAgents" / f"{AGENT_LABEL}.plist"
LOG = Path.home() / "Library" / "Logs" / "susurro.log"


def _post(path: str, body: bytes = b"") -> dict | None:
    try:
        req = urllib.request.Request(BASE + path, data=body, method="POST")
        with urllib.request.urlopen(req, timeout=3) as r:
            return json.loads(r.read())
    except (urllib.error.URLError, ConnectionError, TimeoutError):
        return None


def cmd_speak(args: argparse.Namespace) -> int:
    text = " ".join(args.text) if args.text else sys.stdin.read()
    if not text.strip():
        print("No text.", file=sys.stderr)
        return 1
    params = {k: v for k, v in (("mode", args.mode), ("lang", args.lang)) if v}
    q = "?" + urllib.parse.urlencode(params) if params else ""
    if _post(f"/speak{q}", text.encode()) is not None:
        return 0
    # The app isn't running: play right here, headless.
    from .player import Player

    s = config.load()
    if args.mode:
        s = replace(s, mode=args.mode)
    if args.lang:
        s = replace(s, language=args.lang)
    p = Player()
    p.speak(text, s)
    try:
        while p.busy:
            time.sleep(0.2)
    except KeyboardInterrupt:
        p.stop()
    if p.status.startswith("error"):
        print(p.status, file=sys.stderr)
        return 1
    return 0


def cmd_stop(_: argparse.Namespace) -> int:
    return 0 if _post("/stop") is not None else 1


def cmd_status(_: argparse.Namespace) -> int:
    try:
        with urllib.request.urlopen(BASE + "/status", timeout=2) as r:
            data = json.loads(r.read())
            print(data["status"], f"({data['language']})" if data.get("language") else "")
        return 0
    except (urllib.error.URLError, ConnectionError, TimeoutError):
        print("the app is not running")
        return 1


def cmd_app(_: argparse.Namespace) -> int:
    from .app import run

    run()
    return 0


