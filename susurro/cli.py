def _shell_script() -> str:
    uv = shutil.which("uv") or "/opt/homebrew/bin/uv"
    return f"""# Generated by `susurro install`
log="$HOME/Library/Logs/susurro.log"
exec 2>>"$log"
text="$(cat)"
echo "$(date '+%F %T') shortcut: ${{#text}} chars, args=$#" >&2
[ -z "$text" ] && [ $# -gt 0 ] && text="$*"   # some hosts pass input as arguments
[ -z "$text" ] && exit 0
url="{BASE}/speak"
send() {{ printf '%s' "$text" | /usr/bin/curl -sS -f -m 3 --data-binary @- "$url" >/dev/null; }}
send && exit 0
echo "$(date '+%F %T') app not reachable, starting it" >&2
launchctl kickstart "gui/$(id -u)/{AGENT_LABEL}" 2>/dev/null \\
  || nohup "{uv}" run --project "{PROJECT}" susurro app >>"$log" 2>&1 &
for i in $(seq 1 40); do sleep 0.5; send 2>/dev/null && exit 0; done
echo "$(date '+%F %T') gave up" >&2
afplay /System/Library/Sounds/Basso.aiff
"""


